// Small test games for the live test and test scenarios: a base game from
// tests/fixtures plus variants laid over it, each adding what one kind of
// bug needs. A variant is a folder in tests/fixtures/game-variants whose
// files are copied over the game; its variant.json may add plugins to
// js/plugins.js, values to System.json, maps to MapInfos.json, events to
// Map001 and commands to the village chief's event there, and set the
// stand-in provider's mode, such as lines it refuses.
import fs from "node:fs";
import path from "node:path";
import { root } from "../dependencies.mjs";
import { makePlayable } from "./playable.mjs";

const fixtures = path.join(root, "tests/fixtures");
const overlays = path.join(fixtures, "game-variants");

/** Base games, one of which comes first in a variant list. */
const bases = {
  mz: "The RPG Maker MZ fixture game (tests/fixtures/mz-game).",
  ace: "The RPG Maker VX Ace fixture game (tests/fixtures/ace).",
};

const described = (name) => {
  const file = path.join(overlays, name, "variant.json");
  return JSON.parse(fs.readFileSync(file, "utf8")).description;
};

/** Every variant and what it holds. */
export const variants = {
  ...bases,
  ...Object.fromEntries(
    (fs.existsSync(overlays) ? fs.readdirSync(overlays) : [])
      .sort()
      .map((name) => [name, described(name)]),
  ),
  playable:
    "MZ only: RPG Maker MV's open-source engine, placeholder images and no sound, so the game runs in the release playtest.",
};

const readJson = (file) => JSON.parse(fs.readFileSync(file, "utf8"));

/** Adds `entries` to the game's js/plugins.js. */
function addPlugins(game, entries) {
  const file = path.join(game, "js/plugins.js");
  const text = fs.readFileSync(file, "utf8");
  const list = JSON.parse(
    text.slice(text.indexOf("["), text.lastIndexOf("]") + 1),
  );
  fs.writeFileSync(
    file,
    `// Generated by RPG Maker.\nvar $plugins =\n[\n${[...list, ...entries]
      .map((entry) => JSON.stringify(entry))
      .join(",\n")}\n];\n`,
  );
}

/** Lays the variant `name` over the MZ game at `game`, returning what it
 * asks of the stand-in provider. */
function overlay(game, name) {
  const folder = path.join(overlays, name);
  if (!fs.existsSync(folder))
    throw new Error(
      `No game variant named ${name}; choose from ${Object.keys(variants).join(", ")}.`,
    );
  const variant = readJson(path.join(folder, "variant.json"));
  fs.cpSync(folder, game, {
    recursive: true,
    filter: (source) => path.basename(source) !== "variant.json",
  });
  if (variant.plugins) addPlugins(game, variant.plugins);
  if (variant.maps) {
    const file = path.join(game, "data/MapInfos.json");
    const infos = readJson(file);
    for (const [id, name] of Object.entries(variant.maps))
      infos[Number(id)] = {
        id: Number(id),
        expanded: false,
        name,
        order: Number(id),
        parentId: 0,
        scrollX: 0,
        scrollY: 0,
      };
    fs.writeFileSync(
      file,
      JSON.stringify(Array.from(infos, (info) => info ?? null)),
    );
  }
  if (variant.system) {
    const file = path.join(game, "data/System.json");
    fs.writeFileSync(
      file,
      JSON.stringify({ ...readJson(file), ...variant.system }),
    );
  }
  if (variant.events) {
    // New events on Map001, numbered after its own.
    const file = path.join(game, "data/Map001.json");
    const map = readJson(file);
    for (const event of variant.events)
      map.events.push({ ...event, id: map.events.length });
    fs.writeFileSync(file, JSON.stringify(map));
  }
  if (variant.chief) {
    // The commands go before the end of the chief's first page.
    const file = path.join(game, "data/Map001.json");
    const map = readJson(file);
    const list = map.events[1].pages[0].list;
    list.splice(
      list.findIndex((command) => command.code === 0),
      0,
      ...variant.chief,
    );
    fs.writeFileSync(file, JSON.stringify(map));
  }
  return variant.provider || {};
}

/** The game's folder name, like a Japanese release's. */
export const gameName = (names) =>
  names[0] === "ace" ? "オークの逆襲 体験版" : "魔法少女の冒険 体験版";

/**
 * Builds a game from `names`: a base game first (mz when left out), then
 * variants in order. Returns the stand-in provider's mode the variants ask
 * for, such as lines to refuse.
 * @param {string[]} names
 * @param {string} game the new game folder
 */
export async function makeGame(names, game) {
  const [base, ...rest] = names[0] in bases ? names : ["mz", ...names];
  if (base === "ace") {
    if (rest.length) throw new Error("Variants apply to the MZ game only.");
    // The fixture's other folders are the conversion tests' expected output.
    fs.cpSync(path.join(fixtures, "ace/Data"), path.join(game, "Data"), {
      recursive: true,
    });
    fs.writeFileSync(
      path.join(game, "Game.ini"),
      "[Game]\r\nRTP=RPGVXAce\r\nLibrary=System\\RGSS301.dll\r\nScripts=Data\\Scripts.rvdata2\r\nTitle=オークの逆襲\r\n",
    );
    return {};
  }
  fs.cpSync(path.join(fixtures, "mz-game"), game, { recursive: true });
  const mode = {};
  for (const name of rest)
    if (name !== "playable") Object.assign(mode, overlay(game, name));
  // The engine goes in last, over every variant's data.
  if (rest.includes("playable")) await makePlayable(game);
  return mode;
}
