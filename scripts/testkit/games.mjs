const readJson = (file) => JSON.parse(fs.readFileSync(file, "utf8"));

/** Adds `entries` to the game's js/plugins.js. */
function addPlugins(game, entries) {
  const file = path.join(game, "js/plugins.js");
  const text = fs.readFileSync(file, "utf8");
  const list = JSON.parse(
    text.slice(text.indexOf("["), text.lastIndexOf("]") + 1),
  );
  fs.writeFileSync(
    file,
    `// Generated by RPG Maker.\nvar $plugins =\n[\n${[...list, ...entries]
      .map((entry) => JSON.stringify(entry))
      .join(",\n")}\n];\n`,
  );
}

/** A PNG chunk: its length, type, data and the CRC of type and data. */
function pngChunk(type, data) {
  const head = Buffer.alloc(8);
  head.writeUInt32BE(data.length, 0);
  head.write(type, 4, "latin1");
  const crc = Buffer.alloc(4);
  crc.writeUInt32BE(zlib.crc32(Buffer.concat([head.subarray(4), data])));
  return Buffer.concat([head, data, crc]);
}

/**
 * An RGB PNG with pixels of its own: a gradient keyed on `index` under
 * `noise` rows of random pixels, which no compression shrinks, as a CG's
 * detail does not.
 */
function picture(width, height, index, noise) {
  const header = Buffer.alloc(13);
  header.writeUInt32BE(width, 0);
  header.writeUInt32BE(height, 4);
  header[8] = 8; // bits per channel
  header[9] = 2; // RGB
  const stride = width * 3 + 1;
  const raw = Buffer.alloc(stride * height);
  if (noise) crypto.randomFillSync(raw, 0, stride * Math.min(noise, height));
  for (let y = 0; y < height; y++) {
    raw[y * stride] = 0; // no filter
    if (y < noise) continue;
    for (let x = 0; x < width; x++) {
      const at = y * stride + 1 + x * 3;
      raw[at] = (x + index * 7) & 255;
      raw[at + 1] = (y + index * 13) & 255;
      raw[at + 2] = (index * 31) & 255;
    }
  }
  return Buffer.concat([
    Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]),
    pngChunk("IHDR", header),
    pngChunk("IDAT", zlib.deflateSync(raw, { level: 1 })),
    pngChunk("IEND", Buffer.alloc(0)),
  ]);
}

/** Lays the variant `name` over the MZ game at `game`, returning what it
 * asks of the stand-in provider. */
export function addVariant(game, name) {
  const folder = path.join(overlays, name);
  if (!fs.existsSync(folder))
    throw new Error(
      `No game variant named ${name}; choose from ${Object.keys(variants).join(", ")}.`,
    );
  const variant = readJson(path.join(folder, "variant.json"));
  fs.cpSync(folder, game, {
    recursive: true,
    filter: (source) => path.basename(source) !== "variant.json",
  });
  if (variant.plugins) addPlugins(game, variant.plugins);
  if (variant.maps) {
    const file = path.join(game, "data/MapInfos.json");
    const infos = readJson(file);
    for (const [id, name] of Object.entries(variant.maps))
      infos[Number(id)] = {
        id: Number(id),
        expanded: false,
        name,
        order: Number(id),
        parentId: 0,
        scrollX: 0,
        scrollY: 0,
      };
    fs.writeFileSync(
      file,
      JSON.stringify(Array.from(infos, (info) => info ?? null)),
    );
  }
  if (variant.system) {
    const file = path.join(game, "data/System.json");
    fs.writeFileSync(
      file,
      JSON.stringify({ ...readJson(file), ...variant.system }),
    );
  }
  if (variant.events) {
    // New events on Map001, numbered after its own.
    const file = path.join(game, "data/Map001.json");
    const map = readJson(file);
    for (const event of variant.events)
      map.events.push({ ...event, id: map.events.length });
    fs.writeFileSync(file, JSON.stringify(map));
  }
  if (variant.chief) {
    // The commands go before the end of the chief's first page.
    const file = path.join(game, "data/Map001.json");
    const map = readJson(file);
    const list = map.events[1].pages[0].list;
    list.splice(
      list.findIndex((command) => command.code === 0),
      0,
      ...variant.chief,
    );
    fs.writeFileSync(file, JSON.stringify(map));
  }
  if (variant.assets) {
    // Random bytes, which no compression shrinks, as images and audio are.
    const folder = path.join(game, "img/pictures");
    fs.mkdirSync(folder, { recursive: true });
    const { files, megabytes } = variant.assets;
    const size = Math.floor((megabytes * 1024 * 1024) / files);
    for (let index = 0; index < files; index += 1)
      fs.writeFileSync(
        path.join(folder, `picture${String(index).padStart(5, "0")}.png`),
        crypto.randomBytes(size),
      );
  }
  if (variant.images) {
    // Real PNGs at a game's sizes, each its own pixels, so the Image
    // Manager indexes, previews and groups them as a game's images.
    let index = 0;
    for (const {
      folder,
      name,
      count,
      width,
      height,
      noise = 0,
    } of variant.images) {
      const target = path.join(game, folder);
      fs.mkdirSync(target, { recursive: true });
      for (let number = 0; number < count; number += 1, index += 1)
        fs.writeFileSync(
          path.join(target, `${name}_${String(number).padStart(4, "0")}.png`),
          picture(width, height, index, noise),
        );
    }
  }
  if (variant.emptyRepository)
    // As DazedTL makes it for a record, on its translation branch.
    execFileSync("git", ["-C", game, "init", "-q", "-b", "main"], {
      stdio: "ignore",
    });
  return variant.provider || {};
}

/** The game's folder name, like a Japanese release's. */
