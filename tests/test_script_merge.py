"""A game update carries a translation onto the new release's plugins."""

import json
import unittest
from pathlib import Path

from util.rpgmaker_plugin_registry import format_plugins_js, plugin_entries
from util.version_update.script_merge import merge_plugins, restore_lines


def compact(value):
    return json.dumps(value, ensure_ascii=False, separators=(",", ":"))


def plugin(name, **parameters):
    return {"name": name, "status": True, "description": "", "parameters": parameters}


def quests(*titles):
    return compact([compact({"Title": title, "Reward": "10"}) for title in titles])


def registry(*plugins, canonical):
    """plugins.js as RPG Maker writes it, or as Prepare formats it."""
    native = (
        "// Generated by RPG Maker.\nvar $plugins =\n[\n"
        + ",\n".join(compact(entry) for entry in plugins)
        + "\n];\n"
    )
    return (format_plugins_js(native) if canonical else native).encode("utf-8")


class ScriptMergeTests(unittest.TestCase):
    def test_a_plugin_registry_keeps_translated_settings_and_the_translations_plugins(
        self,
    ):
        # The release adding a quest replaced the whole translated quest list,
        # and registering its own plugin dropped the ones the translation
        # registered beside it.
        for canonical in (False, True):
            base = registry(
                plugin("QuestSystem", QuestDatas=quests("生き抜く風", "ヌシの情報")),
                canonical=canonical,
            )
            translated = registry(
                plugin(
                    "QuestSystem",
                    QuestDatas=quests("Wind of Survival", "Master's Lead"),
                ),
                plugin("HelpFont"),
                plugin("UpdateCheck"),
                plugin("Inspector"),
                canonical=canonical,
            )
            official = registry(
                plugin(
                    "QuestSystem",
                    QuestDatas=quests("生き抜く風", "ヌシの情報", "新しい依頼"),
                ),
                plugin("UpdateCheck"),
                plugin("Battleback"),
                canonical=canonical,
            )
            merged = merge_plugins(base, translated, official)
            self.assertEqual(
                plugin_entries(merged),
                (
                    plugin(
                        "QuestSystem",
                        QuestDatas=quests(
                            "Wind of Survival", "Master's Lead", "新しい依頼"
                        ),
                    ),
                    plugin("HelpFont"),
                    plugin("UpdateCheck"),
                    plugin("Inspector"),
                    plugin("Battleback"),
                ),
            )
            # The release's layout, so the next update lines up with it again.
            self.assertEqual(
                merged.encode("utf-8"),
                registry(*plugin_entries(merged), canonical=canonical),
            )

    def test_a_scripts_translated_lines_return_where_the_release_left_them(self):
        # Git resolved the hunk for the release, and with it the translated
        # line beside the one the release changed.
        base = b"const a = PluginManager.parameters('Title');\nconsole.log(a.text, '\xe5\x86\x92\xe9\x99\xba');\nconst b = 1;\n"
        translated = b"const a = PluginManager.parameters('Title');\nconsole.log(a.text, 'Adventure');\nconst b = 2;\n"
        official = b"const a = PluginManager.parameters(\"Title\");\nconsole.log(a.text, '\xe5\x86\x92\xe9\x99\xba');\nconst b = 1;\n"
        self.assertEqual(
            restore_lines(base, translated, official, official),
            # Code the translation rewrote stays with Git's merge.
            b"const a = PluginManager.parameters(\"Title\");\nconsole.log(a.text, 'Adventure');\nconst b = 1;\n",
        )

    def test_main_js_keeps_loading_the_fixes_where_the_release_won_its_hunk(self):
        # A release that changed main.js beside the line loading the
        # playtest's fixes won the conflict, and the fixes stopped loading.
        import subprocess
        from tempfile import TemporaryDirectory

        from util.playtest import fixes
        from util.version_update.git_workflow import merged_file

        base = b"    onScriptLoad() {\n        PluginManager.setup($plugins);\n    }\n"
        official = base.replace(b"onScriptLoad()", b"onScriptLoad(url)")
        with TemporaryDirectory() as repo:
            subprocess.run(["git", "init", "-q", repo], check=True)

            def blob(raw):
                return (
                    subprocess.run(
                        ["git", "-C", repo, "hash-object", "-w", "--stdin"],
                        input=raw,
                        capture_output=True,
                        check=True,
                    )
                    .stdout.decode()
                    .strip()
                )

            merged = merged_file(
                Path(repo),
                "www/js/main.js",
                blob(fixes.with_loader(base)),
                blob(base),
                blob(official),
            )
        self.assertEqual(merged, fixes.with_loader(official))
